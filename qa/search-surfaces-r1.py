#!/usr/bin/env python3
"""Weplace multi-channel and owned-site prototype QA. Read-only local browser; no external sends."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/"qa"/"search-surfaces-r1"
OUT.mkdir(parents=True,exist_ok=True)
BASE="http://127.0.0.1:4173"
home=(ROOT/"index.html").read_text(encoding="utf-8")
campaign=(ROOT/"november-fast-a-r8.html").read_text(encoding="utf-8")
demo=(ROOT/"examples/moon-site/index.html").read_text(encoding="utf-8")
errors=[];results=[];screens=[]
def ok(condition,label):
 if not condition: raise AssertionError(label)
 results.append(label)
ok(home.count('id="search-surfaces"')==1,"Homepage four-channel section unique")
ok(home.count('role="tab"')==4,"Exactly four platform tabs in homepage")
ok(home.count('role="tabpanel"')==4,"Each tab has dedicated panel")
ok(campaign.count('id="beyond-the-ad"')==1,"November FAST has one compact platform bridge")
ok('href="/#search-surfaces"' in campaign,"November FAST bridge leads to correct homepage anchor")
ok('href="/examples/moon-site/"' in home,"Actual built HTML demo linked from homepage")
ok('href="https://mashcore.co.kr/"' in home,"Mashcore external destination is explicitly linked")
ok('말보다,<br><strong>숫자.</strong>' in home,"First-fold hook is shorter and stronger")
ok('content="noindex,nofollow"' in demo,"Fictional client demo is excluded from indexing")
ok('<details>' in demo and 'href="#questions"' in demo and 'href="#directions"' in demo,"Demo has native functional FAQ and arrival navigation")
ok('AI 검색의 노출·인용·순위를 보장하지 않습니다' in home,"AI search claim boundaries visible")
ok('실제 네이버·Google의 검색 결과 캡처가 아닙니다' in home,"Mock screen label clearly distinguishes fake screenshots")
ok('id="wp-combo-sales"' in home and 'id="wp-combo-inflow"' in home,"Prior numerical visual charts preserved")
ok('id="wp-combo-sales"' in campaign and 'id="nov-wizard"' in campaign,"November FAST chart & inquiry preserved")
ok('weplace-consent-analytics-r1.js' in home and 'weplace-consent-analytics-r1.js' in campaign,"Existing consent analytics preserved")
ok('네이버 플레이스' in home and 'Google 검색·지도' in home and '홈페이지 제작' in home,"Scope labels specific")
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,channel="chrome")
 for width,height in ((320,720),(360,740),(390,844),(768,1024),(1440,900)):
  context=browser.new_context(viewport={"width":width,"height":height},device_scale_factor=1,reduced_motion="reduce")
  def track(e): errors.append(str(e))
  page=context.new_page()
  page.route("https://**",lambda route:route.abort())
  page.on("pageerror",track)
  page.on("response",lambda res: errors.append(f"{res.status} {res.url}") if res.status>=400 and res.url.startswith(BASE) else None)
  response=page.goto(BASE+"/index.html",wait_until="domcontentloaded",timeout=30000)
  ok(response is not None and response.status==200,f"Homepage renders at {width}")
  page.wait_for_timeout(350)
  panel=page.locator("#wp-consent-panel")
  if panel.is_visible():
    panel.locator('[data-wp-choose="rejected"]').click()
  page.locator("#search-surfaces").scroll_into_view_if_needed()
  ok(page.locator('#wp-tab-site[aria-selected="true"]').count()==1,f"Owned website is initially selected at {width}")
  ok(page.locator('#wp-panel-site:visible').count()==1,f"Built website preview is initially visible at {width}")
  for key in ("naver","google","ai","site"):
    page.locator(f"#wp-tab-{key}").click()
    ok(page.locator(f'#wp-tab-{key}[aria-selected="true"]').count()==1,f"{key} tab selected at {width}")
    ok(page.locator(f'#wp-panel-{key}:visible').count()==1,f"{key} preview actually changes at {width}")
    ok(page.locator('#search-surfaces [role="tabpanel"]:visible').count()==1,f"Only one tabpanel visible at {width}")
  page.locator("#wp-tab-site").focus()
  page.keyboard.press("ArrowRight")
  ok(page.locator('#wp-tab-ai[aria-selected="true"]').count()==1,f"Keyboard navigation works at {width}")
  page.locator("#wp-tab-site").click()
  mashcore=page.locator('#wp-panel-site a[href="https://mashcore.co.kr/"]')
  ok(mashcore.count()==1,f"Mashcore is site tab primary external link at {width}")
  ok(mashcore.get_attribute("target")=="_blank" and "noopener" in (mashcore.get_attribute("rel") or ""),f"Mashcore opens safely as separate brand at {width}")
  ok(page.locator('#wp-panel-site a[href="/examples/moon-site/"]').count()==1,f"Weplace-produced fictional demo stays available at {width}")
  page.locator("#search-surfaces").screenshot(path=str(OUT/f"home-surfaces-{width}.png"),animations="disabled",timeout=30000)
  screens.append(f"home-surfaces-{width}.png")
  overflow=page.evaluate("document.documentElement.scrollWidth-document.documentElement.clientWidth")
  ok(overflow<=4,f"No homepage horizontal overflow at {width} ({overflow})")
  # The demo is a real built website with internal navigation, not an image.
  demo_page=context.new_page()
  demo_page.on("pageerror",track)
  demo_page.on("response",lambda res:errors.append(f"{res.status} {res.url}") if res.status>=400 and res.url.startswith(BASE) else None)
  resp=demo_page.goto(BASE+"/examples/moon-site/",wait_until="domcontentloaded",timeout=30000)
  ok(resp is not None and resp.status==200,f"Self-built demo opens at {width}")
  demo_page.locator('a[href="#questions"]').first.click()
  ok(demo_page.locator("#questions").is_visible(),f"FAQ navigation works at {width}")
  demo_page.locator("#questions details").first.locator("summary").click()
  ok(demo_page.locator("#questions details").first.get_attribute("open") is not None,f"FAQ expands at {width}")
  over=demo_page.evaluate("document.documentElement.scrollWidth-document.documentElement.clientWidth")
  ok(over<=4,f"Demo no horizontal overflow at {width} ({over})")
  demo_page.screenshot(path=str(OUT/f"built-site-{width}.png"),full_page=False,animations="disabled")
  screens.append(f"built-site-{width}.png")
  # Existing November FAST remains functional and points back to the detailed channels.
  campaign_page=context.new_page()
  campaign_page.on("pageerror",track)
  campaign_page.goto(BASE+"/november-fast-a-r8.html",wait_until="domcontentloaded",timeout=30000)
  ok(campaign_page.locator("#beyond-the-ad").count()==1,f"Campaign platform bridge rendered at {width}")
  ok(campaign_page.locator("#nov-wizard").count()==1,f"Campaign inquiry retained at {width}")
  campaign_page.locator("#beyond-the-ad").screenshot(path=str(OUT/f"campaign-bridge-{width}.png"),animations="disabled")
  screens.append(f"campaign-bridge-{width}.png")
  over=campaign_page.evaluate("document.documentElement.scrollWidth-document.documentElement.clientWidth")
  ok(over<=4,f"Campaign no horizontal overflow at {width} ({over})")
  context.close()
 nojs=browser.new_context(viewport={"width":390,"height":844},java_script_enabled=False)
 page=nojs.new_page()
 page.goto(BASE+"/index.html",wait_until="domcontentloaded")
 ok(page.locator("#wp-panel-site:visible").count()==1,"No-JS shows the actual homepage demo panel")
 ok(page.locator('noscript').count()>0,"No-JS fallback retained")
 nojs.close()
 browser.close()
report={"checks":len(results),"errors":errors,"screenshots":screens}
(OUT/"report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
print(json.dumps({"checks":len(results),"errors":errors,"screenshots":len(screens)},ensure_ascii=False))
if errors:raise AssertionError(str(errors))
